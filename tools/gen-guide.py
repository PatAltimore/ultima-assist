#!/usr/bin/env python3
"""Generate web/guide-data.js from xu4's module data (engine/module/Ultima-IV/maps.b).

The sidebar's town guides, quest checklist and automap markers are built from
this, so the coordinates come straight from the game data rather than being
typed in by hand.  Run from the repository root:  python tools/gen-guide.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "engine" / "module" / "Ultima-IV" / "maps.b"
OUT = ROOT / "web" / "guide-data.js"

text = SRC.read_text(encoding="utf-8")
blocks = re.split(r"\n    map \(", "\n" + text)[1:]


def bracket(body, key):
    """Contents of the first `key [ ... ]` group in body, or ''."""
    m = re.search(r"\b" + key + r"\s*\[", body)
    if not m:
        return ""
    depth, i = 1, m.end()
    while i < len(body) and depth:
        depth += {"[": 1, "]": -1}.get(body[i], 0)
        i += 1
    return body[m.end():i - 1]


def labels(body):
    out = []
    for m in re.finditer(r"([a-z0-9_]+)\s+(-?\d+)\s*,\s*(-?\d+)(?:\s*,\s*(-?\d+))?", bracket(body, "labels")):
        e = {"k": m.group(1), "x": int(m.group(2)), "y": int(m.group(3))}
        if m.group(4) is not None:
            e["z"] = int(m.group(4))
        out.append(e)
    return out


towns, dungeons, shrines = {}, {}, {}
world = {"labels": [], "moongates": [], "portals": {}}

for blk in blocks:
    head = re.match(r"id:\s*(\d+)\s+type:\s*(\w+)\s+fname:\s*\"([^\"]+)\"", blk)
    if not head:
        continue
    mid, mtype, fname = int(head.group(1)), head.group(2), head.group(3)
    body = blk[head.end():]
    if mtype == "world":
        for m in re.finditer(r"(\d+)\s*,\s*(\d+)\s+save-enter\s+(\d+)\s*,", bracket(body, "portals")):
            world["portals"][int(m.group(3))] = [int(m.group(1)), int(m.group(2))]
        world["labels"] = labels(body)
        for m in re.finditer(r"(\d+)\s*,\s*(\d+)\s*,\s*(\d+)", bracket(body, "moongates")):
            world["moongates"].append({"phase": int(m.group(1)), "x": int(m.group(2)), "y": int(m.group(3))})
    elif mtype == "city":
        c = re.search(r"city \(name:\s*\"([^\"]+)\"\s+type:\s*(\w+)", body)
        roles = {}
        for m in re.finditer(r"([a-z]+)\s+\d+", bracket(body, "roles")):
            roles[m.group(1)] = roles.get(m.group(1), 0) + 1
        towns[mid] = {"name": c.group(1), "kind": c.group(2), "roles": roles, "labels": labels(body)}
    elif mtype == "dungeon":
        d = re.search(r"dungeon \(name:\s*\"([^\"]+)\"", body)
        dungeons[mid] = {"name": d.group(1), "labels": labels(body)}
    elif mtype == "shrine":
        s = re.search(r"shrine \(virtue:\s*\"(\w+)\"\s+mantra:\s*(\w+)", body)
        shrines[mid] = {"virtue": s.group(1), "mantra": s.group(2).upper()}

for table in (towns, dungeons, shrines):
    for mid, e in table.items():
        pos = world["portals"].get(mid)
        if pos:
            e["wx"], e["wy"] = pos

guide = {"towns": towns, "dungeons": dungeons, "shrines": shrines,
         "world": {"labels": world["labels"], "moongates": world["moongates"]}}

OUT.write_text(
    "// Generated by tools/gen-guide.py from engine/module/Ultima-IV/maps.b. Do not edit.\n"
    "var GUIDE = " + json.dumps(guide, indent=1, sort_keys=True) + ";\n",
    encoding="utf-8")
print("wrote", OUT, "towns", len(towns), "dungeons", len(dungeons), "shrines", len(shrines),
      "world labels", len(world["labels"]), "portals", len(world["portals"]))
sys.exit(0)
